export function NavLink({
  href,
  icon,
  exact = false,
  children,
}: {
  href: string;
  icon: string;
  exact?: boolean;
  children: React.ReactNode;
}) {
  const pathname = usePathname();
  const active = exact ? pathname === href : pathname.startsWith(href);
  return (
    <Link href={href} className={"ink-nav-item" + (active ? " active" : "")}>
      {icons[icon]}
      <span>{children}</span>
    </Link>
  );
}
